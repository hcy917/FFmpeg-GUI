"""Probe every media file in the workspace and print a compact report."""
import os

import ffmpeg_gui

ROOT = ffmpeg_gui.workspace_root()


def main(argv):
    root = ffmpeg_gui.workspace_root()
    media = ffmpeg_gui.media_entries()
    if not media:
        print("No media in the library yet. Import a file first.")
        return

    print("Workspace:", root)
    print("Library items:", len(media))
    print("-" * 52)
    for item in media:
        print(f"{item['name']}")
        print(f"  kind={item['kind']} duration={item['duration_ms']}ms")
        info = ffmpeg_gui.probe(os.path.relpath(item["path"], ROOT))
        for line in info.splitlines():
            if line.startswith("format:") or "codec=" in line:
                print("  " + line)
    print("-" * 52)
    print("Done. Report generated by the embedded Python interpreter.")
    ffmpeg_gui.refresh_library()


if __name__ == "__main__":
    main([])
